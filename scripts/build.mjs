// Voyage production build — run by Vercel (see vercel.json → buildCommand).
//
// WHY: the app ships ~27 .jsx files that the browser used to download and
// transpile with Babel-standalone on EVERY cold start (a ~3 MB compiler +
// compiling ~17k lines on the phone). This does the exact same transform
// ONCE at deploy time and serves a single pre-compiled, hashed bundle.
//
// HOW (deliberately boring, to keep behaviour identical):
//   * The file list and order are read from index.html's
//     <script type="text/babel" src="…"> tags, so the build can never drift
//     from what the dev page loads.
//   * Each file is transformed with @babel/standalone using EXACTLY the
//     options the in-browser loader uses (presets react + env, same three
//     plugins). Same compiler, same output semantics (e.g. const → var), so
//     cross-file globals behave as before. No bundler, no module wrapping.
//   * Output goes to out/ (git-ignored). The source tree is untouched:
//     opening index.html locally still runs the Babel dev path.
//
// Run locally:  node scripts/build.mjs   → serve the out/ folder.

import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { execSync } from 'child_process';
import { createRequire } from 'module';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'out');
const require = createRequire(path.join(ROOT, 'package.json'));
process.chdir(ROOT);

// Same compiler version the dev page loads from unpkg.
let Babel;
try { Babel = require('@babel/standalone'); }
catch (_) {
  execSync('npm install --no-save --no-package-lock --silent @babel/standalone@7.29.0', { stdio: 'inherit' });
  Babel = require('@babel/standalone');
}

const html = fs.readFileSync('index.html', 'utf8');
const files = [...html.matchAll(/<script type="text\/babel" src="([^"]+)"><\/script>/g)].map((m) => m[1]);
if (files.length < 10) throw new Error(`Expected the app's text/babel scripts in index.html, found ${files.length}`);

// Mirrors buildBabelOptions() in @babel/standalone's script-tag loader.
const transform = (code, filename) => Babel.transform(code, {
  filename,
  presets: ['react', 'env'],
  plugins: ['transform-class-properties', 'transform-object-rest-spread', 'transform-flow-strip-types'],
  sourceType: 'script',
  comments: false,
  compact: true,
}).code;

const parts = files.map((f) => {
  const src = fs.readFileSync(f, 'utf8');
  // Each file stays its own statement list, exactly like separate <script>s.
  return `/* ${f} */\n${transform(src, f)}\n`;
});
const bundle = '/* Voyage — generated by scripts/build.mjs. Edit src/** instead. */\n' + parts.join('\n');
const hash = crypto.createHash('sha1').update(bundle).digest('hex').slice(0, 10);
const bundleName = `assets/app.${hash}.js`;

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'assets'), { recursive: true });
fs.writeFileSync(path.join(OUT, bundleName), bundle);

// index.html: drop Babel + the text/babel tags; load the one bundle with
// `defer` (runs after parsing, like the Babel loader did on DOMContentLoaded).
let outHtml = html.replace(/[ \t]*<script src="https:\/\/unpkg\.com\/@babel\/standalone[^\n]*\n/, '');
let inserted = false;
outHtml = outHtml.replace(/[ \t]*<script type="text\/babel" src="[^"]+"><\/script>\n/g, (line) => {
  if (inserted) return '';
  inserted = true;
  const indent = line.match(/^[ \t]*/)[0];
  return `${indent}<script defer src="/${bundleName}"></script>\n`;
});
if (!inserted) throw new Error('Could not place the bundle tag in index.html');

// tokens.css gets a content hash too. The service worker serves same-origin
// files cache-first, so on the first launch after a deploy a fixed
// "tokens.css" URL came from the OLD cache while the (hashed) bundle was
// new — fresh components reading variables the stale sheet didn't define.
// A hashed name is never in an old cache, so CSS and JS always match.
const css = fs.readFileSync('tokens.css', 'utf8');
const cssName = `assets/tokens.${crypto.createHash('sha1').update(css).digest('hex').slice(0, 10)}.css`;
fs.writeFileSync(path.join(OUT, cssName), css);
const linkRe = /<link rel="stylesheet" href="tokens\.css" \/>/;
if (!linkRe.test(outHtml)) throw new Error('Could not find the tokens.css link in index.html');
outHtml = outHtml.replace(linkRe, `<link rel="stylesheet" href="/${cssName}" />`);
fs.writeFileSync(path.join(OUT, 'index.html'), outHtml);

// Static files served as-is.
const copy = (rel) => {
  const from = path.join(ROOT, rel);
  if (!fs.existsSync(from)) return;
  fs.cpSync(from, path.join(OUT, rel), { recursive: true });
};
['tokens.css', 'manifest.json', 'offline.html', 'favicon.ico', 'icons'].forEach(copy);

// Service worker: precache the bundle instead of the .jsx sources, and key
// the caches to this build so every deploy replaces them cleanly.
let sw = fs.readFileSync('sw.js', 'utf8');
sw = sw.replace(/^[ \t]*'\/src\/[^']+\.jsx',[^\n]*\n/gm, '');
sw = sw.replace(/(const SHELL_FILES = \[\n)/, `$1  '/${bundleName}',\n  '/${cssName}',\n`);
sw = sw.replace(/const VERSION = '([^']+)';/, (_, v) => `const VERSION = '${v}-${hash}';`);
if (!sw.includes(bundleName)) throw new Error('Could not add the bundle to sw.js SHELL_FILES');
fs.writeFileSync(path.join(OUT, 'sw.js'), sw);

const kb = (n) => (n / 1024).toFixed(0) + ' kb';
console.log(`✓ ${files.length} files → out/${bundleName} (${kb(Buffer.byteLength(bundle))})`);
